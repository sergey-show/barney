type Widen<T> = {
  [K in keyof T]: T[K] extends (...args: infer A) => unknown
    ? (...args: A) => string
    : string;
};

export type Messages = Widen<typeof ru>;

export const catalog: Record<Locale, Messages> = { ru, en };

export function detectLocale(): Locale {
  const stored = localStorage.getItem("barney.locale");
  if (stored === "ru" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function alertTitle(locale: Locale, title: string): string {
  const t = catalog[locale];
  if (title === "Connection lost") return t.alertConnection;
  if (title === "Request failed") return t.alertFailed;
  if (title === "Last step did not finish") return t.alertInterrupted;
  if (title === "Agent error") return t.alertAgent;
  if (title === "Permission needed") return t.alertPermission;
  return title;
}
